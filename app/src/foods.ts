const BY_NAME = new Map<string, NewItem>();
for (const [name, category, days, ...aliases] of ROWS) {
  const item: NewItem = { name, category, days };
  for (const key of [name, ...aliases]) BY_NAME.set(normName(key), item);
}

/** 知っている食材なら、分類と日数の目安を返す */
export function lookup(name: string, staples: Staple[] = []): NewItem | null {
  const key = normName(name);
  if (!key) return null;
  const st = staples.find((s) => normName(s.name) === key);
  if (st) return { name: st.name, category: st.category, days: st.days };
  const hit = BY_NAME.get(key);
  return hit ? { ...hit } : null;
}

/**
 * 「卵、牛乳 納豆」のように食材名だけが並んでいて、すべて知っているものなら、AI を呼ばずに一覧にする。
 * 文章(「〜と〜を買った」など)や知らない言葉がまじるときは null(AI に読んでもらう)。
 */
export function quickParse(text: string, staples: Staple[] = []): NewItem[] | null {
  const tokens = text
    .split(/[、,，・\s　\n]+/)
    .map((t) => t.trim())
    .filter(Boolean);
  if (!tokens.length || tokens.length > 30) return null;
  const out: NewItem[] = [];
  const seen = new Set<string>();
  for (const t of tokens) {
    const hit = lookup(t, staples);
    if (!hit) return null;
    if (seen.has(hit.name)) continue;
    seen.add(hit.name);
    out.push(hit);
  }
  return out;
}

/** まだ使い始めで「いつもの」がないときに出しておくもの */
const STARTERS = ['卵', '牛乳', '納豆', '絹豆腐', '玉ねぎ', 'にんじん', 'キャベツ', '鶏むね肉', '豚こま肉', '食パン', 'ヨーグルト', 'もやし'];

export function quickPicks(staples: Staple[], max = 12): NewItem[] {
  const out: NewItem[] = staples.slice(0, max).map((s) => ({ name: s.name, category: s.category, days: s.days }));
  for (const name of STARTERS) {
    if (out.length >= max) break;
    if (!out.some((o) => normName(o.name) === normName(name))) out.push(lookup(name)!);
  }
  return out;
}
